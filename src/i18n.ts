const interpolate = (template: string, params?: Record<string, string | number>) => {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? `{${key}}`))
}

export const translate = (locale: Locale, key: string, params?: Record<string, string | number>) => {
  const dict = dictionaries[locale] ?? dictionaries.en
  const value = dict[key] ?? dictionaries.en[key] ?? key
  if (typeof value === 'function') return value(params)
  return interpolate(value, params)
}

export const useI18n = () => {
  const locale = useAppStore((state) => state.locale)

  return {
    locale,
    t: (key: string, params?: Record<string, string | number>) => translate(locale, key, params),
  }
}
